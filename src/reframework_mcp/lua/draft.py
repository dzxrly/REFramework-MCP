"""Generate conservative REFramework Lua probes from AccessPlan objects."""

from __future__ import annotations

import json
import math
import re
from typing import Any

from reframework_mcp import __version__
from reframework_mcp.errors import ErrorCode, ReframeworkMCPError
from reframework_mcp.metadata import MetadataRepository
from reframework_mcp.models import AccessOperation, AccessPlan, RootKind
from reframework_mcp.planner.contracts import node_error

_METHOD_SIGNATURE = re.compile(r"^[^:]+::(.+?)\s*->\s*.+$")


def _lua_string(value: str) -> str:
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    encoded = "".join(
        escapes[character]
        if character in escapes
        else f"\\{ord(character):03d}"
        if ord(character) < 32 or ord(character) == 127
        else character
        for character in value
    )
    return '"' + encoded + '"'


def _method_selector(canonical: str) -> str:
    match = _METHOD_SIGNATURE.match(canonical)
    if match:
        return match.group(1).strip()
    return canonical.split("::", 1)[-1].split(" ->", 1)[0].strip()


def _member_name(canonical: str) -> str:
    tail = canonical.split("::", 1)[-1]
    return tail.split(":", 1)[0].split(" {", 1)[0].strip()


class LuaDraftService:
    def __init__(self, metadata: MetadataRepository) -> None:
        self.metadata = metadata

    def draft(
        self,
        plan: AccessPlan,
        *,
        mode: str = "read_only",
        emit_targets: bool = True,
    ) -> dict[str, Any]:
        if mode not in {"read_only", "mutation", "hook"}:
            raise ValueError(f"Unsupported probe mode: {mode}")
        lines = [
            f"-- Generated by REFramework-MCP {__version__}",
            f"-- snapshot: {plan.snapshot_id}",
            f"-- plan: {plan.plan_ref}",
            f"-- goal: {plan.goal}",
            "local function require_value(value, label)",
            "    if value == nil then",
            '        error(label .. " is nil")',
            "    end",
            "    return value",
            "end",
            "",
        ]
        assumptions = list(plan.assumptions)
        sequences: set[str] = set()
        variables: dict[str, str] = {}
        for index, node in enumerate(plan.nodes):
            safe_id = node.node_id.replace("-", "_")
            variable = f"n_{index}_{safe_id}"
            variables[node.node_id] = variable
            input_variable = variables[node.inputs[0]] if node.inputs else None
            problem = node_error(node)
            if problem:
                raise ReframeworkMCPError(ErrorCode.PLAN_INVALID, problem, details={"node_id": node.node_id})
            is_mapped = bool(
                node.inputs
                and node.inputs[0] in sequences
                and node.operation
                not in {
                    AccessOperation.ITERATE,
                    AccessOperation.INDEX,
                    AccessOperation.FILTER,
                    AccessOperation.EMIT,
                }
            )
            generated = self._node_lines(
                node, variable, "item_value" if is_mapped else input_variable, variables
            )
            if is_mapped:
                lines.append(f"local {variable} = probe.map_sequence({input_variable}, function(item_value)")
                lines.extend("    " + line for line in generated)
                lines.extend([f"    return {variable}", "end)"])
            else:
                lines.extend(generated)
            if is_mapped or node.operation in {AccessOperation.ITERATE, AccessOperation.FILTER}:
                sequences.add(node.node_id)
            if not node.nullable and node.operation is not AccessOperation.BIND_CONSTANT:
                lines.append(f"{variable} = require_value({variable}, {_lua_string(node.node_id)})")
            if node.side_effect == "unknown":
                assumptions.append(f"{node.node_id} may have side effects")
            lines.append("")

        if emit_targets:
            for target in plan.targets:
                lines.append(f"probe.emit({_lua_string(target)}, probe.export_value({variables[target]}))")
        lines.append("return true")
        code = "\n".join(lines).rstrip() + "\n"
        unresolved = [
            node.node_id
            for node in plan.nodes
            if node.operation
            in {
                AccessOperation.FILTER,
                AccessOperation.CONSTRUCT_OBJECT,
                AccessOperation.CONSTRUCT_ARRAY,
            }
            and not node.options
        ]
        return {
            "code": code,
            "mode": mode,
            "plan_ref": plan.plan_ref,
            "snapshot_id": plan.snapshot_id,
            "assumptions": sorted(set(assumptions)),
            "unresolved_nodes": unresolved,
        }

    def _node_lines(
        self,
        node: Any,
        variable: str,
        input_variable: str | None,
        variables: dict[str, str],
    ) -> list[str]:
        op = node.operation
        if op is AccessOperation.RESOLVE_ROOT:
            root = node.root
            if root.kind is RootKind.MANAGED_SINGLETON:
                return [f"local {variable} = sdk.get_managed_singleton({_lua_string(root.type_name)})"]
            if root.kind is RootKind.NATIVE_SINGLETON:
                return [f"local {variable} = sdk.get_native_singleton({_lua_string(root.type_name)})"]
            if root.kind is RootKind.STATIC_TYPE:
                return [f"local {variable} = sdk.find_type_definition({_lua_string(root.type_name)})"]
            if root.kind is RootKind.PROVIDED_OBJECT:
                return [f"local {variable} = probe.resolve_object({_lua_string(root.object_ref)})"]
            if root.kind in {RootKind.HOOK_THIS, RootKind.HOOK_ARGUMENT, RootKind.HOOK_RETURN}:
                selector = {
                    RootKind.HOOK_THIS: "this",
                    RootKind.HOOK_ARGUMENT: f"argument:{root.argument_index}",
                    RootKind.HOOK_RETURN: "return",
                }[root.kind]
                return [
                    f"local {variable} = probe.resolve_hook_value("
                    f"{_lua_string(root.hook_ref)}, {_lua_string(selector)})"
                ]
            return [f"local {variable} = probe.resolve_root({_lua_string(root.model_dump_json())})"]

        if op is AccessOperation.RESOLVE_TYPE:
            return [f"local {variable} = sdk.find_type_definition({_lua_string(node.output_type or '')})"]
        if op is AccessOperation.BIND_CONSTANT:
            literal = self._literal(node.value)
            if node.output_type:
                return [
                    f"local {variable} = probe.assert_type({literal}, {_lua_string(node.output_type)}, {self._literal(node.nullable)})"
                ]
            return [f"local {variable} = {literal}"]
        if op is AccessOperation.READ_FIELD:
            field_name = _member_name(node.member.canonical_signature)
            return [
                f"local {variable} = require_value({input_variable}, "
                f"{_lua_string(node.inputs[0])}):get_field({_lua_string(field_name)})"
            ]
        if op is AccessOperation.READ_PROPERTY:
            member = self._member(node)
            getter = str(member.get("getter_name") or "")
            if not getter:
                getter = f"get_{member.get('name', _member_name(node.member.canonical_signature))}()"
            elif "(" not in getter:
                getter += "()"
            return [
                f"local {variable} = require_value({input_variable}, "
                f"{_lua_string(node.inputs[0])}):call({_lua_string(getter)})"
            ]
        if op is AccessOperation.CALL_METHOD:
            selector = _method_selector(node.member.canonical_signature)
            arguments = ", ".join(variables[item] for item in node.arguments)
            suffix = f", {arguments}" if arguments else ""
            return [
                f"local {variable} = require_value({input_variable}, "
                f"{_lua_string(node.inputs[0])}):call({_lua_string(selector)}{suffix})"
            ]
        if op is AccessOperation.CALL_STATIC:
            selector = _method_selector(node.member.canonical_signature)
            declaring_type = node.member.canonical_signature.split("::", 1)[0]
            arguments = ", ".join(variables[item] for item in node.arguments)
            suffix = f", {arguments}" if arguments else ""
            type_var = f"{variable}_type"
            method_var = f"{variable}_method"
            return [
                f"local {type_var} = sdk.find_type_definition({_lua_string(declaring_type)})",
                f"local {method_var} = require_value({type_var}, "
                f"{_lua_string(node.node_id + '_type')}):get_method("
                f"{_lua_string(selector)})",
                f"local {variable} = require_value({method_var}, "
                f"{_lua_string(node.node_id + '_method')})(nil{suffix})",
            ]
        if op is AccessOperation.CAST:
            return [
                f"local {variable} = probe.assert_type({input_variable}, {_lua_string(node.output_type or node.options.get('expected_type', ''))})"
            ]
        if op is AccessOperation.INDEX:
            return [
                f"local {variable} = probe.index_collection({input_variable}, {int(node.options['index'])})"
            ]
        if op is AccessOperation.ITERATE:
            return [
                f"local {variable} = probe.iterate({input_variable}, {node.options.get('offset', 0)}, {node.options.get('limit', 100)})"
            ]
        if op is AccessOperation.FILTER:
            return [
                f"local {variable} = probe.filter_sequence({input_variable}, "
                f"{self._literal(node.options.get('field'))}, {_lua_string(node.options.get('operator', 'eq'))}, "
                f"{self._literal(node.options['value'])}, {node.options.get('offset', 0)}, {node.options.get('limit', 100)})"
            ]
        if op is AccessOperation.ASSERT_RANGE:
            return [
                f"local {variable} = probe.assert_range({input_variable}, "
                f"{self._literal(node.options.get('min'))}, {self._literal(node.options.get('max'))})"
            ]
        if op is AccessOperation.CONSTRUCT_LIST:
            type_name = node.output_type or node.options.get("type_name", "")
            values = ", ".join(variables[item] for item in node.arguments)
            return [f"local {variable} = probe.construct_list({_lua_string(type_name)}, {{{values}}})"]
        if op is AccessOperation.CONSTRUCT_ARRAY:
            type_name = node.output_type or node.options.get("type_name", "")
            values = ", ".join(variables[item] for item in node.arguments)
            return [f"local {variable} = probe.construct_array({_lua_string(type_name)}, {{{values}}})"]
        if op is AccessOperation.CONSTRUCT_DICTIONARY:
            type_name = node.output_type or node.options.get("type_name", "")
            pairs = ", ".join(variables[item] for item in node.arguments)
            return [f"local {variable} = probe.construct_dictionary({_lua_string(type_name)}, {{{pairs}}})"]
        if op is AccessOperation.ASSERT_NON_NULL:
            return [f"local {variable} = require_value({input_variable}, {_lua_string(node.inputs[0])})"]
        if op is AccessOperation.ASSERT_TYPE:
            expected = node.output_type or node.options.get("expected_type", "")
            return [
                f"probe.assert_type({input_variable}, {_lua_string(expected)})",
                f"local {variable} = {input_variable}",
            ]
        if op is AccessOperation.EMIT:
            name = str(node.options.get("name", node.node_id))
            return [
                f"probe.emit({_lua_string(name)}, probe.export_value({input_variable}))",
                f"local {variable} = {input_variable}",
            ]
        return [
            f"-- unresolved operation: {op.value}",
            f"local {variable} = {input_variable or 'nil'}",
        ]

    def _member(self, node: Any) -> dict[str, Any]:
        member_id = node.member.member_id
        if member_id is None:
            return {}
        return self.metadata.member_by_pk(member_id, node.member.snapshot_id) or {}

    @staticmethod
    def _literal(value: Any) -> str:
        if value is None:
            return "nil"
        if value is True:
            return "true"
        if value is False:
            return "false"
        if isinstance(value, int):
            if not -(2**63) <= value < 2**63:
                raise ReframeworkMCPError(
                    ErrorCode.CAPABILITY_UNAVAILABLE, "Lua integer literals require signed 64-bit values"
                )
            return "math.mininteger" if value == -(2**63) else repr(value)
        if isinstance(value, float):
            if not math.isfinite(value):
                raise ReframeworkMCPError(ErrorCode.PLAN_INVALID, "Lua numeric literals must be finite")
            return repr(value)
        if isinstance(value, str):
            return _lua_string(value)
        return _lua_string(json.dumps(value, ensure_ascii=False, sort_keys=True))
